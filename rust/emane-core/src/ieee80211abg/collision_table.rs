pub struct CollisionTable {}

impl CollisionTable {
    pub fn new() -> Self {
        Self {}
    }

    pub fn get_collision_factor(&self, num: i32, cw: i32) -> f32 {
        let mut f_col = 0.0;
        let n = if num < 0 {
            0
        } else if num >= NUM_NBRS as i32 {
            (NUM_NBRS - 1) as i32
        } else {
            num
        };
        let n_idx = n as usize;

        if cw >= 1024 {
            f_col = V1024[n_idx];
        } else if cw >= 512 {
            f_col = self.interpolate(512.0, 1024.0, V512[n_idx], V1024[n_idx], cw as f32);
        } else if cw >= 256 {
            f_col = self.interpolate(256.0, 512.0, V256[n_idx], V512[n_idx], cw as f32);
        } else if cw >= 128 {
            f_col = self.interpolate(128.0, 256.0, V128[n_idx], V256[n_idx], cw as f32);
        } else if cw >= 64 {
            f_col = self.interpolate(64.0, 128.0, V64[n_idx], V128[n_idx], cw as f32);
        } else if cw >= 32 {
            f_col = self.interpolate(32.0, 64.0, V32[n_idx], V64[n_idx], cw as f32);
        } else if cw >= 16 {
            f_col = self.interpolate(16.0, 32.0, V16[n_idx], V32[n_idx], cw as f32);
        } else {
            f_col = V16[n_idx];
        }

        f_col / 100.0
    }

    fn interpolate(&self, x0: f32, x1: f32, y0: f32, y1: f32, x: f32) -> f32 {
        y0 + (x - x0) * (y1 - y0) / (x1 - x0)
    }
}
